const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");
const ts = require("typescript");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "../../src/extension/legacy.ts"), "utf8");
const tree = ts.createSourceFile("legacy.ts", source, ts.ScriptTarget.ES2022, true);
function extract(name, method = false) {
  let found;
  function visit(node) { if ((method ? ts.isMethodDeclaration(node) : ts.isFunctionDeclaration(node)) && node.name?.getText(tree) === name) found = node; ts.forEachChild(node, visit); }
  visit(tree); assert.ok(found);
  const body = found.getText(tree);
  return ts.transpileModule(method ? `({${body}}).${name}` : `${body}\n${name}`,
    { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
}
test("PLAN save rejects missing content and preserves submitted block whitespace", async () => {
  let written;
  const header = vm.runInNewContext(extract("ensurePlanPurposeHeader"));
  const save = vm.runInNewContext(extract("savePlanFromUi", true), {
    stringField: (message, key) => typeof message[key] === "string" ? message[key].trim() : "",
    workspaceRoot: () => "project", safeWorkspacePlanPath: (_root, file) => file, planDirSafe: () => "plans",
    fs: { mkdir: async () => {} }, path, ensurePlanPurposeHeader: header,
    writeWorkspaceTextWithBackup: async (_file, text, assertCurrent) => { assertCurrent(); written = text; },
  });
  const host = { projectContextGeneration: 1, refreshLocalPlanMetadata: async () => {}, refreshExperimentTracesProjectionForCurrentInterest() {},
    persistProjectPlanSelectionState: async () => {}, postState() {} };
  await assert.rejects(save.call(host, { planFile: "p.yaml" }), /缺少 plan 文件或内容/);
  await assert.rejects(save.call(host, { planFile: "p.yaml", text: " \n" }), /缺少 plan 文件或内容/);
  assert.equal(written, undefined);
  const text = "# Generated by SimpleExperiment\nsuite: demo\ncontent: |+\n  value\n\n";
  await save.call(host, { planFile: "p.yaml", text });
  assert.equal(written, text);
});
