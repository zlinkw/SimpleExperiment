export function runWrapperTemplate(): string {
  return [
    "# Generated by ZLK Cluster Orchestrator.",
    "# 用于不改训练代码时捕获 stdout/stderr，并在命令结束后生成标准输出文件。",
    "",
    "from __future__ import annotations",
    "",
    "import argparse",
    "import json",
    "import shlex",
    "import subprocess",
    "import sys",
    "from pathlib import Path",
    "",
    "try:",
    "    from .result_writer import collect_outputs",
    "except Exception:",
    "    from result_writer import collect_outputs",
    "",
    "def main():",
    "    parser = argparse.ArgumentParser(description=\"ZLK 实验运行包装器\")",
    "    parser.add_argument(\"--output-dir\", required=True)",
    "    parser.add_argument(\"--context-json\", default=\"{}\")",
    "    parser.add_argument(\"command\", nargs=argparse.REMAINDER)",
    "    args = parser.parse_args()",
    "    if not args.command:",
    "        raise SystemExit(\"缺少要执行的训练或测试命令。\")",
    "    output_dir = Path(args.output_dir)",
    "    output_dir.mkdir(parents=True, exist_ok=True)",
    "    command = args.command[1:] if args.command[:1] == [\"--\"] else args.command",
    "    process = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)",
    "    (output_dir / \"stdout.log\").write_text(process.stdout or \"\", encoding=\"utf-8\")",
    "    (output_dir / \"stderr.log\").write_text(process.stderr or \"\", encoding=\"utf-8\")",
    "    context = json.loads(args.context_json or \"{}\")",
    "    context.setdefault(\"command\", \" \".join(shlex.quote(item) for item in command))",
    "    collect_outputs(output_dir, context=context, stdout_text=process.stdout, stderr_text=process.stderr)",
    "    sys.exit(process.returncode)",
    "",
    "if __name__ == \"__main__\":",
    "    main()",
    "",
  ].join("\n");
}

