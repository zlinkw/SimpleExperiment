export function outputAdapterTemplate(projectName: string): string {
  const summaryWriter = generatePythonCsvWriterSnippet("write_metrics_summary", standardSummaryColumns.map((column) => column.name));
  const caseWriter = generatePythonCsvWriterSnippet("write_metrics_case", standardCaseColumns.map((column) => column.name));
  return [
    "# Generated by ZLK Cluster Orchestrator.",
    "# 本文件用于把模型输出接入插件的结果解析、质量门禁和论文表格流程。",
    "# 推荐做法：训练或测试结束后，在你的项目代码里 import 本文件，并调用 adapter.collect(...)。",
    "",
    "from __future__ import annotations",
    "",
    "import json",
    "import re",
    "from pathlib import Path",
    "",
    summaryWriter,
    "",
    caseWriter,
    "",
    "SUMMARY_CANDIDATES = [",
    "    \"metrics_summary.csv\",",
    "    \"results.csv\",",
    "    \"work_dirs/results.csv\",",
    "    \"experiments/results/*.csv\",",
    "    \"test_results/summary.csv\",",
    "    \"test_results/detailed_metrics.csv\",",
    "]",
    "",
    "METADATA_COLUMNS = {",
    "    \"experiment_id\", \"attempt_id\", \"study_id\", \"plan_id\", \"suite\", \"method\", \"case\",",
    "    \"dataset\", \"split\", \"fold\", \"seed\", \"epoch\", \"step\", \"timestamp\", \"run_id\",",
    "    \"global_job_id\", \"job_dir\", \"checkpoint_path\", \"config_path\", \"run_status\",",
    "}",
    "",
    "LOWER_IS_BETTER_METRICS = {\"loss\", \"asd\", \"hd95\", \"mae\", \"mse\", \"rmse\", \"error\", \"ece\", \"brier\"}",
    "",
    "def write_env_snapshot(path, command=\"\", seed=\"\"):",
    "    import subprocess",
    "    import sys",
    "    try:",
    "        import torch",
    "    except Exception:",
    "        torch = None",
    "    data = {",
    "        \"schemaVersion\": 1,",
    "        \"git_commit\": subprocess.getoutput(\"git rev-parse HEAD\"),",
    "        \"git_dirty\": bool(subprocess.getoutput(\"git status --porcelain\")),",
    "        \"python\": sys.version.split()[0],",
    "        \"torch\": getattr(torch, \"__version__\", \"\") if torch else \"\",",
    "        \"cuda\": getattr(getattr(torch, \"version\", None), \"cuda\", \"\") if torch else \"\",",
    "        \"gpu_name\": torch.cuda.get_device_name(0) if torch and torch.cuda.is_available() else \"\",",
    "        \"command\": command,",
    "        \"seed\": seed,",
    "    }",
    "    with open(path, \"w\", encoding=\"utf-8\") as f:",
    "        json.dump(data, f, indent=2)",
    "",
    "def pick(row, *keys, default=\"\"):",
    "    lowered = {str(k).lower(): v for k, v in row.items()}",
    "    for key in keys:",
    "        if key in row and row[key] not in (None, \"\"):",
    "            return row[key]",
    "        value = lowered.get(str(key).lower())",
    "        if value not in (None, \"\"):",
    "            return value",
    "    return default",
    "",
    "def numberish(value):",
    "    try:",
    "        float(str(value).strip())",
    "        return True",
    "    except Exception:",
    "        return False",
    "",
    "def read_csv_rows(path):",
    "    import csv",
    "    path = Path(path)",
    "    if not path.exists() or not path.is_file():",
    "        return []",
    "    with open(path, newline=\"\", encoding=\"utf-8-sig\") as f:",
    "        return list(csv.DictReader(f))",
    "",
    "def looks_like_metric_column(name):",
    "    lower = str(name).lower()",
    "    if lower in METADATA_COLUMNS:",
    "        return False",
    "    tokens = [\"dice\", \"dsc\", \"iou\", \"auc\", \"accuracy\", \"acc\", \"f1\", \"loss\", \"hd95\", \"asd\", \"mae\", \"mse\", \"rmse\", \"sensitivity\", \"specificity\", \"precision\", \"recall\"]",
    "    return any(token in lower for token in tokens)",
    "",
    "def summary_row(row, metric, value, context, source_path=\"\"):",
    "    metric = str(metric).strip()",
    "    if not metric or value in (None, \"\"):",
    "        return None",
    "    return {",
    "        \"experiment_id\": pick(row, \"experiment_id\", \"experiment_name\", \"run_id\", \"global_job_id\", default=context.get(\"experiment_id\", \"unknown\")),",
    "        \"attempt_id\": pick(row, \"attempt_id\", \"run_id\", default=context.get(\"attempt_id\", \"attempt-1\")),",
    "        \"study_id\": pick(row, \"study_id\", default=context.get(\"study_id\", \"\")),",
    "        \"plan_id\": pick(row, \"plan_id\", default=context.get(\"plan_id\", \"\")),",
    `        "suite": pick(row, "suite", default=context.get("suite", "${projectName}")),`,
    "        \"method\": pick(row, \"method\", \"case\", default=context.get(\"method\", \"ours\")),",
    "        \"dataset\": pick(row, \"dataset\", default=context.get(\"dataset\", \"unknown\")),",
    "        \"split\": pick(row, \"split\", default=context.get(\"split\", \"test\")),",
    "        \"fold\": pick(row, \"fold\", default=context.get(\"fold\", \"\")),",
    "        \"seed\": pick(row, \"seed\", default=context.get(\"seed\", \"\")),",
    "        \"metric\": metric,",
    "        \"value\": value,",
    "        \"unit\": pick(row, \"unit\", default=\"\"),",
    "        \"higher_is_better\": str(metric).lower() not in LOWER_IS_BETTER_METRICS,",
    "        \"epoch\": pick(row, \"epoch\", default=context.get(\"epoch\", \"\")),",
    "        \"step\": pick(row, \"step\", default=context.get(\"step\", \"\")),",
    "        \"timestamp\": pick(row, \"timestamp\", default=context.get(\"timestamp\", \"\")),",
    "    }",
    "",
    "def normalize_csv_rows(path, rows, context):",
    "    if not rows:",
    "        return []",
    "    headers = list(rows[0].keys())",
    "    lower_headers = {str(h).lower() for h in headers}",
    "    normalized = []",
    "    if \"metric\" in lower_headers and \"value\" in lower_headers:",
    "        for row in rows:",
    "            item = summary_row(row, pick(row, \"metric\"), pick(row, \"value\"), context, str(path))",
    "            if item:",
    "                normalized.append(item)",
    "        return normalized",
    "    metric_columns = [h for h in headers if looks_like_metric_column(h)]",
    "    for row in rows:",
    "        for metric in metric_columns:",
    "            value = row.get(metric, \"\")",
    "            if numberish(value):",
    "                item = summary_row(row, metric, value, context, str(path))",
    "                if item:",
    "                    normalized.append(item)",
    "    return normalized",
    "",
    "def iter_candidate_csv_paths(output_dir, context):",
    "    output_dir = Path(output_dir)",
    "    for pattern in SUMMARY_CANDIDATES:",
    "        yield from output_dir.glob(pattern)",
    "    extras = [context.get(\"result_csv\"), context.get(\"results_csv\"), context.get(\"metrics_csv\")]",
    "    extra_csv_paths = context.get(\"extra_csv_paths\") or []",
    "    if isinstance(extra_csv_paths, (str, Path)):",
    "        extra_csv_paths = [extra_csv_paths]",
    "    extras.extend(extra_csv_paths)",
    "    for item in extras:",
    "        if not item:",
    "            continue",
    "        candidate = Path(item)",
    "        yield candidate",
    "        if not candidate.is_absolute():",
    "            yield output_dir / candidate",
    "",
    "def discover_csv_metrics(output_dir, context):",
    "    rows = []",
    "    seen = set()",
    "    for path in iter_candidate_csv_paths(output_dir, context):",
    "        key = str(Path(path).resolve())",
    "        if key in seen:",
    "            continue",
    "        seen.add(key)",
    "        rows.extend(normalize_csv_rows(path, read_csv_rows(path), context))",
    "    return rows",
    "",
    "METRIC_PATTERN = re.compile(",
    "    r\"(?P<metric>auc|auroc|roc_auc|accuracy|acc|dice|dsc|iou|hd95|asd|loss|f1|sensitivity|specificity|precision|recall|auprc|ece|brier)\"",
    "    r\"\\s*[:=]\\s*(?P<value>-?\\d+(?:\\.\\d+)?)\",",
    "    re.IGNORECASE,",
    ")",
    "",
    "def capture_console_metrics(text, context):",
    "    \"\"\"从 stdout/stderr 中捕获常见深度学习指标。\"\"\"",
    "    rows = []",
    "    for match in METRIC_PATTERN.finditer(text or \"\"):",
    "        metric = match.group(\"metric\")",
    "        if metric.lower() == \"acc\":",
    "            metric = \"accuracy\"",
    "        rows.append({",
    "            \"experiment_id\": context.get(\"experiment_id\", \"unknown\"),",
    "            \"attempt_id\": context.get(\"attempt_id\", \"attempt-1\"),",
    "            \"study_id\": context.get(\"study_id\", \"\"),",
    "            \"plan_id\": context.get(\"plan_id\", \"\"),",
    `            "suite": context.get("suite", "${projectName}"),`,
    "            \"method\": context.get(\"method\", \"ours\"),",
    "            \"dataset\": context.get(\"dataset\", \"unknown\"),",
    "            \"split\": context.get(\"split\", \"test\"),",
    "            \"fold\": context.get(\"fold\", \"\"),",
    "            \"seed\": context.get(\"seed\", \"\"),",
    "            \"metric\": metric,",
    "            \"value\": float(match.group(\"value\")),",
    "            \"unit\": \"\",",
    "            \"higher_is_better\": metric.lower() not in {\"loss\", \"asd\", \"hd95\", \"ece\", \"brier\"},",
    "            \"epoch\": context.get(\"epoch\", \"\"),",
    "            \"step\": context.get(\"step\", \"\"),",
    "            \"timestamp\": context.get(\"timestamp\", \"\"),",
    "        })",
    "    return rows",
    "",
    "def dedupe_rows(rows):",
    "    out = []",
    "    seen = set()",
    "    for row in rows:",
    "        key = tuple(str(row.get(k, \"\")) for k in [\"experiment_id\", \"suite\", \"method\", \"dataset\", \"split\", \"fold\", \"seed\", \"metric\", \"epoch\", \"step\"])",
    "        if key in seen:",
    "            continue",
    "        seen.add(key)",
    "        out.append(row)",
    "    return out",
    "",
    "class OutputAdapterRegistry:",
    "    def __init__(self):",
    "        self._items = {}",
    "",
    "    def register(self, name, adapter_cls):",
    "        self._items[name] = adapter_cls",
    "        return adapter_cls",
    "",
    "    def build(self, name=\"default\", **kwargs):",
    "        cls = self._items.get(name)",
    "        if cls is None:",
    "            raise KeyError(f\"unknown output adapter: {name}\")",
    "        return cls(**kwargs)",
    "",
    "registry = OutputAdapterRegistry()",
    "",
    "def register_adapter(name):",
    "    def deco(cls):",
    "        registry.register(name, cls)",
    "        return cls",
    "    return deco",
    "",
    "@register_adapter(\"default\")",
    "class DefaultDeepLearningAdapter:",
    "    def collect(self, output_dir, context=None, stdout_text=\"\", stderr_text=\"\"):",
    "        context = dict(context or {})",
    "        output_dir = Path(output_dir)",
    "        output_dir.mkdir(parents=True, exist_ok=True)",
    "        summary_rows = []",
    "        summary_rows.extend(discover_csv_metrics(output_dir, context))",
    "        summary_rows.extend(capture_console_metrics(stdout_text, context))",
    "        summary_rows.extend(capture_console_metrics(stderr_text, context))",
    "        summary_rows = dedupe_rows(summary_rows)",
    "        if summary_rows:",
    "            write_metrics_summary(output_dir / \"metrics_summary.csv\", summary_rows)",
    "        write_env_snapshot(output_dir / \"env_snapshot.json\", context.get(\"command\", \"\"), context.get(\"seed\", \"\"))",
    "        (output_dir / \"config_snapshot.yaml\").write_text(context.get(\"config_text\", \"\"), encoding=\"utf-8\")",
    "        files = [p.name for p in [output_dir / \"metrics_summary.csv\", output_dir / \"env_snapshot.json\", output_dir / \"config_snapshot.yaml\"] if p.exists()]",
    "        manifest = {",
    "            \"schemaVersion\": 1,",
    "            \"files\": files,",
    "            \"note\": \"checkpoint 和大权重文件不建议默认同步到本机。\",",
    "        }",
    "        (output_dir / \"artifact_manifest.json\").write_text(json.dumps(manifest, indent=2), encoding=\"utf-8\")",
    "        return manifest",
    "",
    "def collect_outputs(output_dir, context=None, stdout_text=\"\", stderr_text=\"\", adapter=\"default\", extra_csv_paths=None):",
    "    context = dict(context or {})",
    "    if extra_csv_paths is not None:",
    "        context[\"extra_csv_paths\"] = extra_csv_paths",
    "    return registry.build(adapter).collect(output_dir, context=context, stdout_text=stdout_text, stderr_text=stderr_text)",
    "",
    "if __name__ == \"__main__\":",
    "    demo = \"DSC: 0.912 HD95: 4.2 loss=0.13\"",
    "    collect_outputs(\"zlk_cluster/demo_output\", {\"experiment_id\": \"demo\", \"suite\": \"demo\", \"dataset\": \"demo\", \"split\": \"test\", \"seed\": 42, \"results_csv\": \"work_dirs/results.csv\"}, demo)",
    "",
  ].join("\n");
}

